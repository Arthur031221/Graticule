// Writes src/palette-data.js from d3-scale-chromatic so the ColorBrewer values
// are copied from a package and never typed by hand.
import { writeFile } from "node:fs/promises";
import * as chromatic from "d3-scale-chromatic";
import { rgb } from "d3-color";

const hex = (c) => rgb(c).formatHex();
const SEQUENTIAL = [
  "Blues",
  "Greens",
  "Oranges",
  "Purples",
  "Reds",
  "Greys",
  "YlGnBu",
  "YlOrRd",
  "GnBu",
  "OrRd",
  "PuBuGn",
];
const DIVERGING = ["RdBu", "BrBG", "PRGn", "PuOr", "PiYG"];
const CONTINUOUS = ["Viridis", "Cividis", "Magma", "Plasma"];

const palettes = {};
for (const name of SEQUENTIAL) {
  const table = chromatic[`scheme${name}`];
  palettes[name.toLowerCase()] = {
    type: "sequential",
    classes: Object.fromEntries(range(3, 9).map((k) => [k, table[k]])),
  };
}
for (const name of DIVERGING) {
  const table = chromatic[`scheme${name}`];
  palettes[name.toLowerCase()] = {
    type: "diverging",
    classes: Object.fromEntries(range(3, 11).map((k) => [k, table[k]])),
  };
}
for (const name of CONTINUOUS) {
  const interpolate = chromatic[`interpolate${name}`];
  const classes = {};
  for (const k of range(3, 9)) classes[k] = range(0, k - 1).map((i) => hex(interpolate(0.04 + (0.92 * i) / (k - 1))));
  palettes[name.toLowerCase()] = { type: "sequential", classes };
}
palettes["okabe-ito"] = {
  type: "categorical",
  colors: ["#0072B2", "#E69F00", "#009E73", "#CC79A7", "#56B4E9", "#D55E00", "#F0E442", "#555555"],
};
palettes["tol-bright"] = {
  type: "categorical",
  colors: ["#4477AA", "#EE6677", "#228833", "#CCBB44", "#66CCEE", "#AA3377", "#BBBBBB"],
};

function range(from, to) {
  return Array.from({ length: to - from + 1 }, (_, i) => from + i);
}

const body = JSON.stringify(palettes, null, 1).replace(
  /\[\s+("#[0-9a-fA-F]{6}"(?:,\s+"#[0-9a-fA-F]{6}")*)\s+\]/g,
  (_, items) => `[${items.replace(/\s+/g, " ")}]`,
);
await writeFile(
  new URL("../src/palette-data.js", import.meta.url),
  `// Generated by scripts/build-palettes.mjs. ColorBrewer (Apache 2.0, Brewer and Harrower)\n// and viridis family values come from d3-scale-chromatic.\nexport const PALETTE_DATA = ${body};\n`,
);
